declare(strict_types=1);

namespace Zero\Blog\Model;

use Magento\Framework\App\ResourceConnection;
use Magento\Store\Model\StoreManagerInterface;

/**
 * Permanent (301) redirects to blog posts, kept in Magento's URL rewrites
 * (Marketing > URL Rewrites, entity type "zero-blog"): from a post's old URL
 * when its URL key changes, and from a post's address on the blog it was
 * imported from.
 */
class Redirects
{
    public const ENTITY_TYPE = 'zero-blog';

    public function __construct(
        private readonly ResourceConnection $resource,
        private readonly StoreManagerInterface $storeManager
    ) {
    }

    /**
     * @param int[] $storeIds 0 = every store view
     */
    public function add(string $fromPath, string $toPath, array $storeIds, int $postId): void
    {
        $fromPath = trim($fromPath, '/');
        $toPath = trim($toPath, '/');
        if ($fromPath === '' || $fromPath === $toPath) {
            return;
        }
        $connection = $this->resource->getConnection();
        $table = $this->resource->getTableName('url_rewrite');
        foreach ($this->expand($storeIds) as $storeId) {
            // A redirect away from the new address would loop: drop it.
            $connection->delete($table, ['request_path = ?' => $toPath, 'store_id = ?' => $storeId, 'entity_type = ?' => self::ENTITY_TYPE]);
            // Older redirects to the old address now go straight to the new one.
            $connection->update($table, ['target_path' => $toPath], [
                'target_path = ?' => $fromPath, 'store_id = ?' => $storeId, 'entity_type = ?' => self::ENTITY_TYPE,
            ]);
            $taken = $connection->fetchOne(
                $connection->select()->from($table, ['url_rewrite_id'])
                    ->where('request_path = ?', $fromPath)->where('store_id = ?', $storeId)
            );
            if ($taken !== false) {
                continue; // a product, category or CMS page uses that address
            }
            $connection->insert($table, [
                'entity_type' => self::ENTITY_TYPE,
                'entity_id' => $postId,
                'request_path' => $fromPath,
                'target_path' => $toPath,
                'redirect_type' => 301,
                'store_id' => $storeId,
                'is_autogenerated' => 0,
                'description' => 'Zero Blog',
            ]);
        }
    }

    /**
     * @param int[] $storeIds
     * @return int[]
     */
    private function expand(array $storeIds): array
    {
        if (!$storeIds || in_array(0, $storeIds, true)) {
            return array_map(static fn ($store) => (int) $store->getId(), array_values($this->storeManager->getStores()));
        }

        return $storeIds;
    }
}
